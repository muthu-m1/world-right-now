// Builds assets/map.js: world land outlines as one SVG path, in a plain
// equirectangular projection so the page can place cities with simple math.
// Data: Natural Earth 1:110m via the world-atlas package (public domain).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoEquirectangular, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const W = 1000;
const TOP = 84;      // northernmost latitude shown
const BOTTOM = -58;  // southernmost latitude shown (drops Antarctica)
const k = W / 360;   // pixels per degree
const H = Math.round((TOP - BOTTOM) * k);

const projection = geoEquirectangular()
  .scale(W / (2 * Math.PI))
  .translate([W / 2, TOP * k]);
const path = geoPath(projection).digits(1);

const out = `// Generated by scripts/build-map.mjs. Natural Earth land outlines (public domain).
window.WRN_MAP = ${JSON.stringify({ w: W, h: H, top: TOP, k, land: path(land) })};
`;
writeFileSync(new URL("../assets/map.js", import.meta.url), out);
console.log(`assets/map.js: ${W}x${H}, ${out.length} bytes`);
